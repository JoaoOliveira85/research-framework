#!/usr/bin/env python3
"""Render the prompt corpus into ``docs/prompts/`` (issue #280).

Not one of the framework's live prompts was reproduced outside the code that
builds it. A clean-room reimplementer inherited the orchestration graph and
the JSON Schemas the outputs must satisfy, but not one line of the text that
makes a model produce conforming output — 2,374 lines of Jinja, five agent
definitions and 26 skill files, all of them reachable only by knowing where
to look.

This script is the fix, and the rule it enforces is: **never hand-copy a
prompt.** Every artifact below is either rendered here from its source or
recorded here by path and content hash. Editing a rendered copy is pointless
— the guard re-derives it from the source and fails.

Two treatments, and the split is deliberate:

* **Rendered verbatim** (``docs/prompts/<slug>.md``) — the Jinja templates.
  Their text does not otherwise exist in the repo in the form a model sees:
  they are rendered into a generated vault at scaffold time, so reading the
  repo tells you the template, not the prompt. Reproducing them verbatim is
  the only way the corpus carries them.

* **Recorded, not copied** — the 26 ``.agents/skills/*/SKILL.md`` files.
  These are already standalone, verbatim, tracked files. Copying them into
  ``docs/prompts/`` would create a second source for the same bytes, which
  is the exact duplication issue #281 was filed about. The manifest names
  each one, the stage that dispatches it, and its hash — so drift is still
  caught, without a second copy to drift *from*.

Every prompt-shaped file in the tree must be classified as one of the two,
or listed in ``NOT_A_PROMPT`` with a reason. A guard that had to be told
about each new prompt would fail open the first time someone forgot; this
one fails closed on anything it has not been told about.

Usage::

    python scripts/render_prompt_corpus.py            # write
    python scripts/render_prompt_corpus.py --check    # verify, write nothing

Exit codes: 0 clean, 1 drifted (``--check``), 2 an unclassified prompt file.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DIR = REPO_ROOT / "docs" / "prompts"
MANIFEST = OUTPUT_DIR / "README.md"

_GENERATED_BANNER = (
    "<!-- GENERATED by scripts/render_prompt_corpus.py — DO NOT EDIT. "
    "Edit the source named below, then re-run the script. -->"
)


@dataclass(frozen=True)
class Prompt:
    """One prompt artifact.

    ``source`` is repo-relative. ``slug`` is the output basename for a
    rendered artifact, or ``None`` for one that is recorded only.
    """

    source: str
    role: str
    dispatched_by: str
    slug: str | None = None

    @property
    def is_rendered(self) -> bool:
        return self.slug is not None


